import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { browser, base, root } from './helpers.mjs';

const instance = await browser();
const context = await instance.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage(), checks = [], errors = [], external = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (request.url().startsWith('http') && new URL(request.url()).origin !== base) external.push(request.url()); });
const images = path.join(root, 'docs/images');
await mkdir(images, { recursive: true });
try {
  const baseline = await (await context.request.get(base + '/api/system/database')).json();
  const aiBefore = await (await context.request.get(base + '/api/ai/status')).json();
  await page.goto(base);
  await page.getByText('History ready', { exact: true }).waitFor();
  async function compareExample(example) {
    await page.getByRole('button', { name: 'New comparison', exact: true }).click();
    await page.getByLabel('Example comparison', { exact: true }).selectOption(example);
    await page.getByRole('button', { name: 'Load example', exact: true }).click();
    await page.getByText('Example loaded. Compare the versions when you’re ready.', { exact: true }).waitFor();
    await page.getByRole('checkbox', { name: 'Save to history', exact: true }).uncheck();
    await page.getByRole('button', { name: 'Compare specifications', exact: true }).click();
    await page.locator('.report-title').waitFor();
    await page.getByText('UNSAVED REVIEW', { exact: true }).waitFor();
  }
  await compareExample('breaking');
  assert.equal(await page.locator('.finding-row').count(), 3);
  assert.equal(await page.locator('.summary-card.breaking strong').innerText(), '3');
  await page.getByLabel('Search findings', { exact: true }).fill('schema_type_changed');
  assert.equal(await page.locator('.finding-row').count(), 1);
  await page.getByLabel('Search findings', { exact: true }).fill('');
  await page.locator('.finding-row').filter({ hasText: 'HTTP operation removed' }).click();
  assert.match(await page.locator('.evidence-value.before pre').innerText(), /parameters/);
  assert.match(await page.locator('.evidence-value.after').innerText(), /Not declared/);
  if (await page.getByRole('button', { name: 'Dismiss message', exact: true }).count()) await page.getByRole('button', { name: 'Dismiss message', exact: true }).click();
  const mask = baseline.saved_comparisons > 0 ? [page.locator('.recent-list'), page.locator('.nav-count')] : [];
  await page.screenshot({ path: path.join(images, 'relay-workspace.png'), fullPage: true, mask, maskColor: '#171f30' });
  checks.push('real original breaking example has three breaking findings, working search, and exact removal evidence');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('tab', { name: /Findings/ }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(images, 'relay-mobile.png'), fullPage: true });
  await page.locator('.finding-row').filter({ hasText: 'HTTP operation removed' }).click();
  await page.locator('.evidence-intro').waitFor({ state: 'visible' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(images, 'relay-evidence.png'), fullPage: true });
  checks.push('mobile findings and evidence screenshots use real source values without horizontal overflow');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await compareExample('additive');
  assert.equal(await page.locator('.finding-row').count(), 2);
  assert.equal(await page.locator('.summary-card.breaking strong').innerText(), '0');
  assert.equal(await page.locator('.summary-card.informational strong').innerText(), '2');
  checks.push('real additive example has two informational findings and no breaking findings');
  await compareExample('identical');
  assert.equal(await page.locator('.finding-row').count(), 0);
  assert.equal(await page.locator('.summary-card.breaking strong').innerText(), '0');
  checks.push('identical example has zero findings with declared coverage limits');
  const after = await (await context.request.get(base + '/api/system/database')).json();
  const aiAfter = await (await context.request.get(base + '/api/ai/status')).json();
  assert.equal(after.saved_comparisons, baseline.saved_comparisons);
  assert.equal(after.stored_result_bytes, baseline.stored_result_bytes);
  assert.equal(aiAfter.calls_this_process_today, aiBefore.calls_this_process_today);
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  assert.deepEqual(await page.evaluate(() => [localStorage.length, sessionStorage.length]), [0, 0]);
  checks.push('demo leaves history and model-call count unchanged, with no external page requests or browser storage');
  const report = { status: 'passed', mode: 'actual Chrome and local FastAPI/offline workers; original unsaved examples', checks, history_writes: 0, model_calls: 0, existing_history_masked: baseline.saved_comparisons > 0, screenshots: ['docs/images/relay-workspace.png', 'docs/images/relay-mobile.png', 'docs/images/relay-evidence.png'], uncaught_errors: errors, external_page_requests: external };
  await writeFile(path.join(root, 'docs/section-7-demo.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify({ status: 'passed', checks: checks.length, history_writes: 0, model_calls: 0 }));
} finally { await context.close(); await instance.close(); }
